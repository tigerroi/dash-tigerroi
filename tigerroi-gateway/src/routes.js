/**
 * Mencari rute gateway berdasarkan slug URL
 */
export function findGatewayRoute(slug) {
  if (!slug) return null;
  const clean = String(slug)
    .toLowerCase()
    .trim()
    .replace(/^\/+ |\/+$/g, "");
  return GATEWAY_ROUTES[clean] || null;
}
